---@type BetterMacroIcons
local ns = select(2, ...)

-- dataset.lua — tooling to build and validate the bundled baseline (data/spellterms.lua).
--   /bmi export  dumps the pooled terms (bundle + live scans, merged) as a ready-to-commit file.
--   /bmi diff    reports what live scans have discovered BEYOND the shipped bundle — so you can
--                tell, e.g. a week after a patch, whether auto-discovery is still finding new
--                spells (keep scanning) or has gone quiet (safe to pause until the next patch).
-- Curated aliases live in a separate store (db.aliases) and are intentionally NOT considered
-- here — this compares spell/racial terms only. Removable: delete this file + its .toc line.

-- Dedup-append a space-bounded name into bucket[fileID] (mirrors scan.lua's addName).
local function addTerm(bucket, fileID, name)
    local cur = bucket[fileID]
    if not cur then
        bucket[fileID] = " " .. name .. " "
    elseif not cur:find(" " .. name .. " ", 1, true) then
        bucket[fileID] = cur .. name .. " "
    end
end

local function stores()
    local db = ns.db or {}
    return db.spellTermsBySpec or {}, db.spellTermsByRace or {}, db.spellTermsByClass or {}
end

-- Merge live + bundled section-sets into one, deduped per icon. `canon` (optional) folds keys
-- to their canonical id (races), so a stale variant key collapses into the canonical section.
local function mergeBuckets(liveT, bunT, canon)
    local out = {}
    local function fold(src)
        for key, section in pairs(src) do
            local k = (canon and type(key) == "number" and canon(key)) or key
            local dst = out[k] or {}
            out[k] = dst
            for fileID, names in pairs(section) do
                for name in names:gmatch("%S+") do addTerm(dst, fileID, name) end
            end
        end
    end
    fold(bunT or {})
    fold(liveT)
    return out
end

-- Emit a bucket-table as sorted Lua-literal lines (deterministic → clean diffs).
local function emitBuckets(lines, name, buckets)
    lines[#lines + 1] = "  " .. name .. " = {"
    local keys = {}
    for k in pairs(buckets) do keys[#keys + 1] = k end
    table.sort(keys)
    for _, k in ipairs(keys) do
        local fids = {}
        for f in pairs(buckets[k]) do fids[#fids + 1] = f end
        table.sort(fids)
        local parts = {}
        for _, f in ipairs(fids) do
            parts[#parts + 1] = "[" .. f .. "]=" .. ("%q"):format(buckets[k][f])
        end
        lines[#lines + 1] = "    [" .. k .. "] = {" .. table.concat(parts, ",") .. "},"
    end
    lines[#lines + 1] = "  },"
end

ns:registerCommand("export", nil, function()
    local bySpec, byRace, byClass = stores()
    local bundled = ns.bundledSpellTerms or {}
    local lines = {
        "---@class BetterMacroIcons",
        "---@field bundledSpellTerms table",
        "local ns = select(2, ...)",
        "",
        "-- Bundled baseline spell/racial search terms (generated by /bmi export). scan.lua's",
        "-- rebuildMerged folds this under live scans, so a fresh install has coverage out of the box.",
        "ns.bundledSpellTerms = {",
    }
    emitBuckets(lines, "bySpec", mergeBuckets(bySpec, bundled.bySpec))
    emitBuckets(lines, "byRace", mergeBuckets(byRace, bundled.byRace, ns.CanonRace))
    emitBuckets(lines, "byClass", mergeBuckets(byClass, bundled.byClass))
    lines[#lines + 1] = "}"
    ns.ShowReport("BMI Export — paste into data/spellterms.lua", lines)
end, "Dump the pooled spell terms as data/spellterms.lua (copy window)")

-- Names not present in the bundled section for the same icon (i.e. newly discovered live).
local function newNames(liveNames, bunNames)
    local news = {}
    for name in liveNames:gmatch("%S+") do
        if not (bunNames or ""):find(" " .. name .. " ", 1, true) then
            news[#news + 1] = name
        end
    end
    return news
end

ns:registerCommand("diff", nil, function()
    local bySpec, byRace, byClass = stores()
    local bundled = ns.bundledSpellTerms or {}
    local bunSpec, bunRace, bunClass = bundled.bySpec or {}, bundled.byRace or {}, bundled.byClass or {}

    -- Canonicalise live race keys so a stale variant id (e.g. a pre-alias Haranir 91) doesn't
    -- read as "new" against the canonical bundle.
    local raceCanon = mergeBuckets(byRace, nil, ns.CanonRace)

    local lines, total = {}, 0
    local function report(live, bun, nameOf)
        local keys = {}
        for k in pairs(live) do keys[#keys + 1] = k end
        table.sort(keys)
        for _, k in ipairs(keys) do
            local bunSec = bun[k] or {}
            local fids = {}
            for f in pairs(live[k]) do fids[#fids + 1] = f end
            table.sort(fids)
            for _, f in ipairs(fids) do
                local news = newNames(live[k][f], bunSec[f])
                if #news > 0 then
                    total = total + #news
                    lines[#lines + 1] = ("  %s [%d]: %s"):format(nameOf(k), f, table.concat(news, ", "))
                end
            end
        end
    end

    report(bySpec, bunSpec, function(id)
        local _, name = GetSpecializationInfoByID(id)
        return name or ("spec " .. id)
    end)
    report(raceCanon, bunRace, function(id)
        local info = type(id) == "number" and C_CreatureInfo.GetRaceInfo(id)
        return (info and info.raceName) or ("race " .. tostring(id))
    end)
    report(byClass, bunClass, function(id)
        local info = type(id) == "number" and C_CreatureInfo.GetClassInfo(id)
        return (info and info.className) or ("class " .. tostring(id))
    end)

    if total == 0 then
        ns.ShowReport("BMI Diff", { "live scan matches the bundled baseline — auto-discovery has found nothing new." })
    else
        table.insert(lines, 1, ("live scan has %d spell term(s) not in the bundled baseline:"):format(total))
        ns.ShowReport("BMI Diff", lines)
    end
end, "Compare live scan vs bundled baseline — new discoveries only (aliases excluded)")
